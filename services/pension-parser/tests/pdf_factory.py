"""Builds synthetic PDFs for the parser tests. No real statement is ever used.

Every document is assembled from plain PDF objects so a test states exactly what is inside:
a text layer, a page size, a compressed stream, a damaged cross-reference table.
"""

from __future__ import annotations

import zlib
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from io import BytesIO

LETTER = (612.0, 792.0)
A4 = (595.0, 842.0)

# A short synthetic statement: enough text for the text layer to be used without OCR.
SYNTHETIC_STATEMENT_LINES = (
    "Synthetic Pension Fund - Annual Statement",
    "Participant: Test Person (synthetic)",
    "Statement period: 2025-01-01 to 2025-12-31",
    "Opening balance: 10,000.00",
    "2025-03-31 Employee contribution 250.00",
    "2025-06-30 Employer contribution 500.00",
    "2025-09-30 Employee contribution 250.00",
    "2025-12-31 Administration fee 12.50",
    "2025-12-31 Annual investment return 830.25",
    "Closing balance: 11,817.75",
    "This document is generated by a test and describes no real person or account.",
    "All amounts are invented for the purpose of exercising the statement parser.",
)


@dataclass(frozen=True)
class Page:
    content: bytes = b""
    size: tuple[float, float] = LETTER
    compress: bool = False
    user_unit: float | None = None
    # Already Flate-compressed content, written as is.
    deflated: bytes | None = None


def _escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def text_content(lines: Iterable[str], *, font_size: int = 11, top: int = 740) -> bytes:
    ops = [f"BT /F1 {font_size} Tf {font_size + 3} TL 50 {top} Td"]
    for line in lines:
        ops.append(f"({_escape(line)}) Tj T*")
    ops.append("ET")
    return "\n".join(ops).encode("latin-1")


def build_pdf(pages: Sequence[Page]) -> bytes:
    """Writes a complete PDF 1.7 file with a valid cross-reference table."""
    objects: list[bytes] = []

    def add(body: bytes) -> int:
        objects.append(body)
        return len(objects)

    catalog = add(b"")  # filled in below
    pages_obj = add(b"")
    font = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    kids: list[int] = []
    for page in pages:
        if page.deflated is not None:
            data, filter_entry = page.deflated, b" /Filter /FlateDecode"
        elif page.compress:
            data, filter_entry = zlib.compress(page.content, 9), b" /Filter /FlateDecode"
        else:
            data, filter_entry = page.content, b""
        stream = add(
            b"<< /Length %d%s >>\nstream\n" % (len(data), filter_entry) + data + b"\nendstream"
        )
        width, height = page.size
        unit = b" /UserUnit %g" % page.user_unit if page.user_unit else b""
        kids.append(
            add(
                b"<< /Type /Page /Parent %d 0 R /MediaBox [0 0 %g %g]%s "
                b"/Resources << /Font << /F1 %d 0 R >> >> /Contents %d 0 R >>"
                % (pages_obj, width, height, unit, font, stream)
            )
        )
    objects[catalog - 1] = b"<< /Type /Catalog /Pages %d 0 R >>" % pages_obj
    objects[pages_obj - 1] = b"<< /Type /Pages /Kids [%s] /Count %d >>" % (
        b" ".join(b"%d 0 R" % kid for kid in kids),
        len(kids),
    )

    out = BytesIO()
    out.write(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(b"%d 0 obj\n" % number + body + b"\nendobj\n")
    xref = out.tell()
    out.write(b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1))
    for offset in offsets:
        out.write(b"%010d 00000 n \n" % offset)
    out.write(
        b"trailer\n<< /Size %d /Root %d 0 R >>\nstartxref\n%d\n%%%%EOF\n"
        % (len(objects) + 1, catalog, xref)
    )
    return out.getvalue()


def statement_pdf(pages: int = 1) -> bytes:
    """A readable synthetic statement with a text layer."""
    return build_pdf([Page(text_content(SYNTHETIC_STATEMENT_LINES))] * pages)


def short_text_pdf(lines: Sequence[str] = ("ANNUAL STATEMENT 2025",), pages: int = 1) -> bytes:
    """Too little text for the text layer to count, so the parser falls back to OCR."""
    return build_pdf([Page(text_content(lines, font_size=36, top=600))] * pages)


def blank_pdf(pages: int = 1, size: tuple[float, float] = LETTER, user_unit=None) -> bytes:
    return build_pdf([Page(b"", size=size, user_unit=user_unit)] * pages)


def encrypted_pdf(user_password: str = "synthetic-password", owner_password=None) -> bytes:
    """The synthetic statement, encrypted with RC4 (no extra crypto library needed)."""
    from pypdf import PdfReader, PdfWriter

    writer = PdfWriter(clone_from=PdfReader(BytesIO(statement_pdf())))
    writer.encrypt(
        user_password=user_password,
        owner_password=owner_password or "synthetic-owner",
        algorithm="RC4-128",
    )
    out = BytesIO()
    writer.write(out)
    return out.getvalue()


def truncated_pdf() -> bytes:
    data = statement_pdf()
    return data[: len(data) // 2]


def garbage_pdf(size: int = 4096) -> bytes:
    """A PDF header followed by bytes that are not PDF syntax."""
    return b"%PDF-1.7\n" + bytes((index * 37 + 11) % 256 for index in range(size))


def decompression_bomb_pdf(expanded_mb: int = 200) -> bytes:
    """One page whose compressed content stream expands to `expanded_mb` megabytes."""
    compressor = zlib.compressobj(9)
    chunk = b" " * (1024 * 1024)
    data = b"".join(compressor.compress(chunk) for _ in range(expanded_mb)) + compressor.flush()
    return build_pdf([Page(deflated=data)])


def slow_text_pdf(operations: int = 400_000) -> bytes:
    """A small file whose text layer takes seconds to read: many tiny text operations."""
    ops = [b"BT /F1 1 Tf"]
    ops.extend(b"1 0 Td (a) Tj" for _ in range(operations))
    ops.append(b"ET")
    return build_pdf([Page(b"\n".join(ops), compress=True)])
